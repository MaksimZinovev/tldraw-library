#!/usr/bin/env node
// Phase C — build paste snippets + READMEs from out/blobs.json + out/manifest.json.
//
// Snippet envelope mirrors what tldraw itself copies to the clipboard (and what the
// tldraw-snippets repo distributes): the asset records stay raw JSON; everything else
// (schema, shapes, rootShapeIds, bindings) is LZ-String `compressToBase64`-ed into
// data.otherCompressed.
//
// Output: library/<category>/README.md per category, rewritten root README.md.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import LZString from 'lz-string';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LIB = path.join(ROOT, 'library');
const OUT = path.join(ROOT, 'out');

const blobs = JSON.parse(fs.readFileSync(path.join(OUT, 'blobs.json'), 'utf8'));
const manifest = JSON.parse(fs.readFileSync(path.join(OUT, 'manifest.json'), 'utf8'));

function envelopeFor(content) {
	const { schema, shapes, rootShapeIds, bindings } = content;
	const assets = content.assets || [];
	const other = JSON.stringify({ schema, shapes, rootShapeIds, bindings });
	return {
		type: 'application/tldraw',
		kind: 'content',
		version: 3,
		data: {
			assets,
			otherCompressed: LZString.compressToBase64(other),
		},
	};
}

const byCat = new Map();
for (const s of manifest) {
	if (!byCat.has(s.cat)) byCat.set(s.cat, []);
	byCat.get(s.cat).push(s);
}

function snippetHtmlDiv(content) {
	const env = envelopeFor(content);
	return `<meta charset="utf-8"><div data-tldraw="">${JSON.stringify(env)}</div>`;
}

function sanitizeDescription(s) {
	const keys = (s.keys || '').split(' ').filter(Boolean).slice(0, 6).join(' · ');
	return keys;
}

function catReadme(catId, catName, items) {
	const lines = [];
	lines.push(`# ${catName}`);
	lines.push('');
	lines.push(`${items.length} element${items.length === 1 ? '' : 's'}. Expand an element, copy the snippet block, then paste into [tldraw](https://tldraw.com) or tldraw Desktop.`);
	lines.push('');
	for (const s of items) {
		const blob = blobs[`${s.cat}/${s.id}`];
		if (!blob) {
			console.error(`missing blob for ${s.cat}/${s.id}`);
			continue;
		}
		lines.push(`---`);
		lines.push('');
		lines.push(`## ${s.name}`);
		lines.push('');
		lines.push(`<img src="./${s.id}.svg" alt="${s.name}" width="${s.width}">`);
		lines.push('');
		lines.push('<details>');
		lines.push('<summary>Copy/paste snippet</summary>');
		lines.push('');
		lines.push('```html');
		lines.push(snippetHtmlDiv(blob));
		lines.push('```');
		lines.push('');
		lines.push('</details>');
		if (sanitizeDescription(s)) {
			lines.push('');
			lines.push(`<sub>Search terms: ${sanitizeDescription(s)}</sub>`);
		}
		lines.push('');
	}
	fs.writeFileSync(path.join(LIB, catId, 'README.md'), lines.join('\n'));
	console.log(`library/${catId}/README.md (${items.length})`);
}

const CAT_ORDER = ['plan', 'furniture', 'system', 'flow', 'interface'];
for (const catId of CAT_ORDER) catReadme(catId, byCat.get(catId)?.[0]?.catName || catId, byCat.get(catId) || []);

// Root README
const counts = CAT_ORDER.map(id => [id, byCat.get(id)?.length || 0]);
const total = counts.reduce((a, [, n]) => a + n, 0);
const tocRows = counts
	.map(([id, n]) => `| [${byCat.get(id)[0].catName}](./library/${id}/README.md) | ${n} | ${byCat.get(id).map(s => `\`${s.id}\``).join(' · ')} |`)
	.join('\n');

const readme = `# tldraw Library — Ferroprint symbols for tldraw

Paste-ready snippet blocks for **${total} diagram symbols** — floor-plan, furniture, system, flow and
interface shapes from [Ferroprint](https://github.com/bjarneo/ferroprint), converted to native tldraw
clipboard content. Works on [tldraw.com](https://tldraw.com) and in tldraw Desktop.

## How to use

1. Pick a category below.
2. Expand an element's **Copy/paste snippet** block and copy the \`\`\`html fenced content.
3. Paste into a tldraw canvas. The image (and its default label, if it has one) lands as real tldraw shapes, ready to move, resize and style.

## Categories

| Category | Elements | Symbol ids |
|---|---|---|
${tocRows}

Each element also has an SVG preview next to its snippet in the category pages.

## How these were generated

Everything here is generated by \`scripts/build.mjs\` (Ferroprint symbol sources → SVG), then
\`scripts/capture-blobs.mjs\` (live tldraw Desktop editor → native clipboard content) and
\`scripts/emit-readmes.mjs\` (this README set). See \`scripts/\` for the pipeline. Regeneration needs
the Ferroprint checkout next to this repo (upstream commit \`e501013\`, 2026-10-08) and tldraw Desktop
running.

## Provenance & style notes

- Symbols are rendered with Ferroprint's **white** theme: blue ink \`#24398a\` on transparent, so they sit naturally on tldraw's light canvas.
- Default labels (e.g. *Up* on stairs) are separate editable tldraw **text** shapes grouped with the image; the symbols themselves are images (baked SVG), so strokes/labels of the drawing are not individually editable.
- Ferroprint's UML class boxes, cloud icons and templates are not included (they are dynamic in Ferroprint); connectors are not carried over — use tldraw's own connectors.

## License

MIT — see [LICENSE](./LICENSE). Generated shapes derive from Ferroprint (no upstream license file at time of generation; symbol definitions © Ferroprint authors, used as the drawing source of truth).
`;

fs.writeFileSync(path.join(ROOT, 'README.md'), readme);
console.log('README.md (root) written');